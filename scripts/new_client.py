#!/usr/bin/env python3
"""
Scaffold a new client workflow directory from templates.

Usage:
    python scripts/new_client.py --org-slug my_clinic --workflow-name eligibility_check --flow-type dialout
    python scripts/new_client.py --org-slug my_clinic --workflow-name patient_intake --flow-type dialin

This creates:
    clients/<org_slug>/<workflow_name>/
    ├── __init__.py
    ├── flow_definition.py
    └── services.yaml (reference copy from demo_clinic_alpha)

After running:
1. Customize flow_definition.py with your workflow logic
2. Update services.yaml with your API keys and configuration
3. Register the workflow in the organization's MongoDB document
4. Add frontend routes if needed
"""

