def main():
    parser = argparse.ArgumentParser(
        description="Scaffold a new client workflow directory",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python scripts/new_client.py --org-slug acme_clinic --workflow-name insurance_check --flow-type dialout
  python scripts/new_client.py --org-slug acme_clinic --workflow-name appointment_booking --flow-type dialin

After running:
  1. Edit clients/<org>/<workflow>/flow_definition.py to customize the conversation flow
  2. Copy and customize services.yaml from demo_clinic_alpha
  3. Register the workflow in your organization's MongoDB document
  4. Add frontend routes if needed
        """
    )
    parser.add_argument(
        "--org-slug",
        required=True,
        help="Organization slug (e.g., 'acme_clinic'). Use snake_case."
    )
    parser.add_argument(
        "--workflow-name",
        required=True,
        help="Workflow name (e.g., 'eligibility_check'). Use snake_case."
    )
    parser.add_argument(
        "--flow-type",
        required=True,
        choices=["dialout", "dialin"],
        help="Flow type: 'dialout' for outbound calls, 'dialin' for inbound calls"
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing files"
    )

    args = parser.parse_args()

    # Validate names (should be snake_case)
    for name, value in [("org-slug", args.org_slug), ("workflow-name", args.workflow_name)]:
        if not value.replace("_", "").isalnum():
            print(f"Error: {name} should only contain letters, numbers, and underscores")
            sys.exit(1)
        if value[0].isdigit():
            print(f"Error: {name} should not start with a number")
            sys.exit(1)

    # Create directory structure
    workflow_dir = PROJECT_ROOT / "clients" / args.org_slug / args.workflow_name
    workflow_dir.mkdir(parents=True, exist_ok=True)

    # Generate class name from workflow name
    class_name = snake_to_pascal(args.workflow_name) + "Flow"

    # Files to create
    files = {
        "__init__.py": create_init_file(),
        "flow_definition.py": (
            create_dialout_flow(class_name, args.workflow_name)
            if args.flow_type == "dialout"
            else create_dialin_flow(class_name, args.workflow_name)
        ),
        "services.yaml": create_services_yaml_reference(),
    }

    # Create files
    created = []
    skipped = []
    for filename, content in files.items():
        filepath = workflow_dir / filename
        if filepath.exists() and not args.force:
            skipped.append(filename)
            continue
        filepath.write_text(content)
        created.append(filename)

    # Print summary
    print(f"\n{'='*60}")
    print("Client workflow scaffolded successfully!")
    print(f"{'='*60}")
    print(f"\nDirectory: clients/{args.org_slug}/{args.workflow_name}/")
    print(f"Flow type: {args.flow_type}")
    print(f"Flow class: {class_name}")

    if created:
        print("\nCreated files:")
        for f in created:
            print(f"  - {f}")

    if skipped:
        print("\nSkipped (already exist, use --force to overwrite):")
        for f in skipped:
            print(f"  - {f}")

    print(f"\n{'='*60}")
    print("Next steps:")
    print("{'='*60}")
    print(f"""
1. Customize the flow definition:
   vim clients/{args.org_slug}/{args.workflow_name}/flow_definition.py

2. Copy and configure services.yaml:
   cp clients/demo_clinic_alpha/eligibility_verification/services.yaml \\
      clients/{args.org_slug}/{args.workflow_name}/services.yaml
   vim clients/{args.org_slug}/{args.workflow_name}/services.yaml

3. Register workflow in MongoDB (update your organization document):
   {{
     "workflows": {{
       "{args.workflow_name}": {{
         "enabled": true,
         "patient_schema": {{ ... }}
       }}
     }}
   }}

4. Test the workflow:
   # Start backend locally
   ./dev.sh

   # Create a test patient and initiate a call
""")


if __name__ == "__main__":
    main()
