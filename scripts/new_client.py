sys.path.insert(0, str(PROJECT_ROOT))


def snake_to_pascal(name: str) -> str:
    """Convert snake_case to PascalCase. e.g., eligibility_check -> EligibilityCheck"""
    return "".join(word.capitalize() for word in name.split("_"))


